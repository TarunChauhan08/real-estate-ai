import { type MiddlewareConsumer, Module, type NestModule } from '@nestjs/common';
import { APP_GUARD } from '@nestjs/core';
import { ThrottlerGuard, ThrottlerModule } from '@nestjs/throttler';
import { RequestIdMiddleware } from './common/middleware/request-id.middleware';
import { rateLimitOptions } from './common/rate-limit/rate-limit';
import { AppConfigService } from './config/app-config.service';
import { AppConfigModule } from './config/config.module';
import { DatabaseModule } from './database/database.module';
import { AuditModule } from './modules/audit/audit.module';
import { AuthModule } from './modules/auth/auth.module';
import { HealthModule } from './modules/health/health.module';
import { MembershipsModule } from './modules/memberships/memberships.module';

@Module({
  imports: [
    AppConfigModule,
    ThrottlerModule.forRootAsync({ inject: [AppConfigService], useFactory: rateLimitOptions }),
    DatabaseModule,
    AuditModule,
    MembershipsModule,
    AuthModule,
    HealthModule,
  ],
  providers: [
    // Registered before the auth guard so abusive clients are rejected before any DB work.
    { provide: APP_GUARD, useClass: ThrottlerGuard },
  ],
})
export class AppModule implements NestModule {
  configure(consumer: MiddlewareConsumer): void {
    consumer.apply(RequestIdMiddleware).forRoutes('*');
  }
}
